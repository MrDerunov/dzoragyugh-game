const TIER_BY_HEALTH: { min: number; tier: VerdictTier; title: string }[] = [
  { min: 75, tier: 'saved', title: 'Деревня спасена' },
  { min: 40, tier: 'survived', title: 'Деревня выжила' },
  { min: 15, tier: 'repair', title: 'Деревня требует ремонта' },
  { min: 1, tier: 'gata', title: 'Деревня держится на гате' },
  { min: 0, tier: 'dead', title: 'Деревня не выжила' },
];

/** «Официальная оценка ущерба» (геймдизайн §7–8, §26). */
export function getVerdict(stats: GameStats, random: () => number = Math.random): Verdict {
  if (stats.taps === 0) {
    return { title: 'Наблюдатель ОБСЕ', diagnosis: 'В происходящее не вмешивался.', tier: 'survived' };
  }
  if (stats.villageHealth === 100 && stats.mistakes === 0 && stats.taps > 0) {
    return { title: 'НЕВОЗМОЖНЫЙ РЕЗУЛЬТАТ', diagnosis: 'Проверяем, точно ли вы ученик.', tier: 'saved' };
  }
  const row = TIER_BY_HEALTH.find((r) => stats.villageHealth >= r.min) ?? TIER_BY_HEALTH[TIER_BY_HEALTH.length - 1]!;
  const pool = POOLS[row.tier];
  const diagnosis = pool[Math.floor(random() * pool.length)]!;
  return { title: row.title, diagnosis, tier: row.tier };
}
